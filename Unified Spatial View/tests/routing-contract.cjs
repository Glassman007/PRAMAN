const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const index=read('index.html'),styles=read('styles.css'),bootstrap=read('map/bootstrap.js'),shell=read('map/ui-shell.js'),bridge=read('layer1-integration.js');
assert.match(index,/classList\.add\('final-ui', 'ui-shell-booting'\)/,'production entry must hide the pre-final shell before async content paints');
assert.match(index,/src="\.\/map\/bootstrap\.js"/,'index must enter through the production bootstrap');
assert.doesNotMatch(index,/type="importmap"|three-0\.180\.0|map\/main\.js/,'index must not expose deleted 3D entry points');
assert.match(bootstrap,/prepareUIShell\(\)/,'bootstrap must prepare the final shell');
assert.match(bootstrap,/import\('\.\/flat-main\.js'\)/,'bootstrap must enter the 2D production renderer directly');
assert.doesNotMatch(bootstrap,/URLSearchParams|\bmode\b|import\(['"]\.\/main\.js['"]\)|pilot|calibration/,'obsolete renderer route aliases must be gone');
assert.match(shell,/body\.classList\.add\('final-ui','ui-shell-booting'\)/);
assert.match(shell,/body\.classList\.remove\('ui-shell-booting'\);body\.classList\.add\('ui-shell-ready'\)/);
assert.match(styles,/\.final-ui\.ui-shell-booting \.layer-sidebar[\s\S]*display:none!important/);
assert.match(index,/class="back-link" href="\.\.\/layer1\/index\.html"/,'dashboard back link must return to Layer 1');
assert.match(bridge,/new URL\('\.\/index\.html', script\.src\)\.href/,'Layer 1 bridge must target the production index');
assert.match(bridge,/event\.stopImmediatePropagation\(\)/,'bridge must suppress obsolete competing click handlers');
assert.match(bridge,/window\.location\.assign\(target\)/,'bridge must navigate directly to production entry');
console.log('PASS: direct 2D production entry, final-shell bootstrap, Layer 1 bridge and back contract.');
